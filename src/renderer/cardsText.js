export function textFor(language) {
  return TEXT[LANGUAGES.includes(language) ? language : 'pt'];
}

export function translatePage(root, text) {
  root.documentElement.lang = text.htmlLang;
  root.title = text.pageTitle;
  for (const element of root.querySelectorAll('[data-t]')) element.textContent = text[element.dataset.t];
  for (const element of root.querySelectorAll('[data-t-title]')) element.title = text[element.dataset.tTitle];
  for (const element of root.querySelectorAll('[data-t-aria]')) element.setAttribute('aria-label', text[element.dataset.tAria]);
  for (const element of root.querySelectorAll('[data-t-placeholder]')) element.placeholder = text[element.dataset.tPlaceholder];
}
